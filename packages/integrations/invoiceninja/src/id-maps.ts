/** `null` when `alpha2` (case-insensitive) has no entry — never throws. */
export function ninjaCountryIdForAlpha2(alpha2: string | null | undefined): number | null {
  if (alpha2 === null || alpha2 === undefined) return null;
  const key = alpha2.trim().toUpperCase();
  return key in NINJA_COUNTRY_ID_BY_ALPHA2 ? NINJA_COUNTRY_ID_BY_ALPHA2[key]! : null;
}

/** `null` when `iso4217` (case-insensitive) has no entry — never throws. */
export function ninjaCurrencyIdForIso4217(iso4217: string | null | undefined): number | null {
  if (iso4217 === null || iso4217 === undefined) return null;
  const key = iso4217.trim().toUpperCase();
  return key in NINJA_CURRENCY_ID_BY_ISO4217 ? NINJA_CURRENCY_ID_BY_ISO4217[key]! : null;
}
