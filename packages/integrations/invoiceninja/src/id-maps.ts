/**
 * Two static id maps the widened client push needs (loxep-cd3.1,
 * `expense-entry-design.md` section 2's mapping table): Invoice Ninja's
 * `country_id` and `settings.currency_id` are NUMERIC ids private to its own
 * `countries`/`currencies` tables, not ISO codes, and Loxep only ever stores
 * ISO-3166-1 alpha-2 / ISO-4217 alpha codes.
 *
 * SOURCE-VERIFIED against `database/seeders/CountriesSeeder.php` and
 * `database/seeders/CurrenciesSeeder.php` (`invoiceninja/invoiceninja`,
 * `v5-stable` branch, commit `dcc27c94dc0c463341676a0c19b89d927c3d1287`,
 * fetched 2026-08-15) plus the two follow-on migrations that add currencies
 * beyond the seeder's original list
 * (`2021_09_23_100629_add_currencies.php`, `2023_03_10_100629_add_currencies.php`,
 * `2024_10_18_211558_updated_currencies.php`) — all three are already folded
 * into the seeder file at the commit above, so {@link NINJA_CURRENCY_ID_BY_ISO4217}
 * is the complete, current set. Field names (`country_id`, `settings.currency_id`,
 * `settings.payment_terms`) were cross-checked against `app/Models/Client.php`'s
 * `$fillable` and `app/Http/Requests/Client/StoreClientRequest.php`'s
 * validation rules. These maps remain source-verified rather than
 * authenticated-live-verified. Re-verify with `GET /api/v1/statics` or a
 * throwaway instance's client-edit country/currency dropdowns before relying
 * on them for a disputed push, per the design's own instruction.
 *
 * ## The finding that simplifies this file: `country_id` IS the ISO numeric code
 *
 * Every row in `CountriesSeeder.php` carries an `id` equal to its own
 * `country_code` field (the ISO-3166-1 NUMERIC code, e.g. `840` for the
 * United States) — confirmed by diffing all 249 rows. Invoice Ninja's
 * `country_id` is therefore not an arbitrary internal id to reverse-engineer;
 * it is the standard ISO-3166-1 numeric code, and {@link NINJA_COUNTRY_ID_BY_ALPHA2}
 * is exactly the alpha-2 -> numeric table any ISO-3166-1 reference gives.
 * `settings.currency_id` has NO such shortcut — Invoice Ninja assigns its own
 * sequence (`USD` is `1`, `GBP` is `2`, …, with some gaps from removed
 * currencies), so {@link NINJA_CURRENCY_ID_BY_ISO4217} is transcribed
 * verbatim from the seeder and cannot be derived from a standard.
 *
 * Both maps are deliberately narrow: a code with no entry returns `null` (via
 * the lookup helpers below) rather than throwing, so a push for a
 * counterparty in an unmapped jurisdiction/currency still succeeds — it just
 * omits `country_id`/`settings.currency_id` rather than failing the whole
 * push, matching this package's existing "adapter-side, best-effort
 * projection" posture.
 */

